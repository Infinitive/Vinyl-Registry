// Helper to normalize strings for robust fuzzy matching
function normalizeText(str?: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .replace(/['’"“”]/g, '')
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Match an owned album to a ResearchRecord from the Research Master v2.
 * Uses deterministic ID matching, artist + title matching, and explicit edge cases (Doechii, etc.).
 */
export function findMatchingResearchRecord(album?: {
  id?: string;
  artist?: string;
  title?: string;
}): ResearchRecord | undefined {
  if (!album) return undefined;

  // 1. Check direct seed ID match (seed-record-001 -> id 1)
  if (album.id && album.id.startsWith('seed-record-')) {
    const seedIndex = parseInt(album.id.replace('seed-record-', ''), 10);
    if (!isNaN(seedIndex) && seedIndex >= 1 && seedIndex <= RESEARCH_MASTER_RECORDS.length) {
      const match = RESEARCH_MASTER_RECORDS[seedIndex - 1];
      if (match && match.id === seedIndex) {
        return match;
      }
    }
  }

  const normArtist = normalizeText(album.artist);
  const normTitle = normalizeText(album.title);

  // Guard against empty values
  if (!normArtist && !normTitle) return undefined;

  // 2. Explicit Doechii edge case: User listed "Denial Is a River", research is "Alligator Bites Never Heal"
  if (normArtist.includes('doechii')) {
    const doechiiRecord = RESEARCH_MASTER_RECORDS.find((r) => normalizeText(r.artist).includes('doechii'));
    if (doechiiRecord) return doechiiRecord;
  }

  // 3. Exact normalized artist + title
  if (normArtist && normTitle) {
    const exactMatch = RESEARCH_MASTER_RECORDS.find(
      (r) => normalizeText(r.artist) === normArtist && normalizeText(r.title) === normTitle
    );
    if (exactMatch) return exactMatch;
  }

  // 4. Normalized title prefix or fuzzy match for special punctuation/editions (e.g. Star-Crossed vs Star-Crossed (Limited Edition Picture Disc))
  if (normArtist && normTitle) {
    const fuzzyMatch = RESEARCH_MASTER_RECORDS.find((r) => {
      const rArtist = normalizeText(r.artist);
      const rTitle = normalizeText(r.title);

      if (rArtist !== normArtist) {
        // Check for artist normalization differences like "hello goodbye" vs "hellogoodbye" or "mxmtoon"
        const rArtistFlat = rArtist.replace(/\s+/g, '');
        const aArtistFlat = normArtist.replace(/\s+/g, '');
        if (rArtistFlat !== aArtistFlat) return false;
      }

      if (rTitle === normTitle) return true;
      if (rTitle.length >= 3 && normTitle.length >= 3) {
        if (normTitle.startsWith(rTitle) || rTitle.startsWith(normTitle)) return true;
      }
      return false;
    });

    return fuzzyMatch;
  }

  return undefined;
}

/**
 * Non-destructively enrich an existing Album record with Phase 6 Research metadata.
 * Strictly preserves user-generated data, IDs, ratings, and custom personal notes.
 * When forceUpdateClassification is true (e.g. during Phase 6.2 migration), updates genres/styles to research baseline.
 */
export function enrichAlbumWithResearch(
  album: Album,
  research?: ResearchRecord | null,
  forceUpdateClassification = false
): Album {
  if (!research) return album;

  // Title handling: for Doechii, user originally listed track title "Denial Is a River";
  // the research establishes the record as the album "Alligator Bites Never Heal".
  let updatedTitle = album.title;
  const artistLower = (album.artist || '').toLowerCase();
  const titleLower = (album.title || '').toLowerCase();
  if (
    artistLower.includes('doechii') &&
    (titleLower.includes('denial') || titleLower.includes('alligator'))
  ) {
    updatedTitle = 'Alligator Bites Never Heal';
  }

  // Parse genres, styles, packagingExtras if provided as semicolon-delimited strings
  const parsedGenres = research.genre
    ? research.genre.split(';').map((g) => g.trim()).filter(Boolean)
    : undefined;

  const parsedStyles = research.style
    ? research.style.split(';').map((s) => s.trim()).filter(Boolean)
    : undefined;

  const parsedExtras = research.packagingExtras
    ? research.packagingExtras.split(';').map((e) => e.trim()).filter(Boolean)
    : undefined;

  return {
    ...album,
    title: updatedTitle,

    // Metadata: use research value unless user already explicitly populated a custom value
    releaseYear: album.releaseYear ?? (research.releaseYear ?? undefined),
    genres: forceUpdateClassification
      ? (parsedGenres ?? undefined)
      : (album.genres && album.genres.length > 0 ? album.genres : parsedGenres),
    styles: forceUpdateClassification
      ? (parsedStyles ?? undefined)
      : (album.styles && album.styles.length > 0 ? album.styles : parsedStyles),
    label: album.label || (research.label ?? undefined),
    country: album.country || (research.country ?? undefined),
    format: album.format || (research.format ?? undefined),
    edition: album.edition || (research.edition ?? undefined),
    variant: album.variant || (research.variant ?? undefined),
    packagingExtras:
      album.packagingExtras && album.packagingExtras.length > 0
        ? album.packagingExtras
        : parsedExtras,
    discCount: album.discCount ?? (research.discCount ?? undefined),
    rpm: album.rpm || (research.rpm ? String(research.rpm) : undefined),
    catalogNumber: album.catalogNumber || (research.catalogNumber ?? undefined),

    // Phase 6 explicit research fields:
    physicalIdentifier: research.physicalIdentifier ?? album.physicalIdentifier ?? undefined,
    identifierType: research.identifierType || album.identifierType || undefined,
    barcode: research.barcode ?? album.barcode ?? undefined,
    matrixRunout: research.matrixRunout ?? album.matrixRunout ?? undefined,
    pressingPlant: research.pressingPlant ?? album.pressingPlant ?? undefined,
    pressingCountry: research.pressingCountry ?? album.pressingCountry ?? undefined,
    pressingYear: research.pressingYear ?? album.pressingYear ?? undefined,
    vinylWeight: research.vinylWeight ?? album.vinylWeight ?? undefined,
    researchStatus: research.researchStatus || album.researchStatus || undefined,
    confidence: research.confidence || album.confidence || undefined,
    physicalConfirmation: research.physicalConfirmation || album.physicalConfirmation || undefined,
    researchNotes: research.notes || album.researchNotes || undefined,
    researchConflicts: research.conflicts || album.researchConflicts || undefined,

    // Personal user notes and rating are strictly preserved
    notes: album.notes,
    personalRating: album.personalRating,
    purchasePrice: album.purchasePrice,
    purchaseDate: album.purchaseDate,
  };
}

